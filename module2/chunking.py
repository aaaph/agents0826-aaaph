"""
М2 — чанкінг: видно розмір чанка, перетин і те, що вони ламають.

У нашій KB чанкінг не потрібен — одне правило вже атомарне (~40 токенів).
Але щойно замість 14 коротких правил приходить справжній документ на
кілька сторінок, розбивати доводиться. І тут з'являються дві біди:

  чанк замалий  → факт відірваний від умови («120 грн» без «якщо 5+ днів»)
  чанк завеликий → у промпт їде багато зайвого, релевантне тоне

Перетин (overlap) — страховка від першої біди: сусідні чанки частково
повторюють одне одного, тому факт на межі потрапляє в обидва.

    python chunking.py            # розбиття з підсвіткою перетину
    python chunking.py --compare  # де саме рвуться пов'язані факти
"""

import sys
import pathlib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

# Реальний уривок умов — те, що прийшло б із PDF замість готових правил
DOC = """Розділ 4. Порядок повернення вартості послуг доставки.

4.1. Клієнт має право звернутися за поверненням вартості доставки у разі
порушення оператором заявленого строку доставки відправлення.

4.2. Якщо фактичний строк доставки перевищує заявлений на 5 і більше днів,
клієнт має право на повернення вартості доставки. Розмір повернення
дорівнює фактично сплаченій вартості доставки і для тарифу «Експрес»
становить 120 грн. Вартість вкладення при цьому не повертається.

4.5. Повернення здійснюється на той самий спосіб оплати, яким було
сплачено послугу, протягом 14 банківських днів з моменту прийняття
рішення за зверненням клієнта.

4.7. Якщо відправлення повернуто відправнику через невірну адресу,
вказану самим відправником, вартість доставки не повертається,
оскільки послугу було надано в повному обсязі.

Розділ 7. Компенсація за втрачене вкладення.

7.3. Компенсація за втрачене вкладення виплачується в межах оголошеної
цінності відправлення після завершення процедури розшуку. Строк розшуку
для внутрішніх відправлень становить до 10 робочих днів."""


def tokens(text: str) -> int:
    """Груба оцінка: для української ~1.3 токена на слово. Точно — у tiktoken."""
    return int(len(text.split()) * 1.3)


def chunk(text: str, size: int, overlap: int) -> list[str]:
    """Найпростіший чанкер: по словах, з фіксованим перетином.

    size і overlap — у ТОКЕНАХ (приблизних). Крок = size - overlap.
    """
    words = text.split()
    per_chunk = max(1, int(size / 1.3))          # скільки слів у чанку
    step = max(1, int((size - overlap) / 1.3))   # на скільки слів зсуваємось
    out = []
    for start in range(0, len(words), step):
        piece = words[start:start + per_chunk]
        if not piece:
            break
        out.append(" ".join(piece))
        if start + per_chunk >= len(words):
            break
    return out


def show(chunks: list[str], size: int, overlap: int) -> None:
    print(f"\nрозмір {size} ток. · перетин {overlap} ток. "
          f"({overlap / size:.0%}) → {len(chunks)} чанків")
    print("─" * 78)
    prev_words = []
    for i, c in enumerate(chunks, 1):
        words = c.split()
        # скільки слів на початку збігається з хвостом попереднього чанка
        dup = 0
        if prev_words:
            for k in range(min(len(words), len(prev_words)), 0, -1):
                if prev_words[-k:] == words[:k]:
                    dup = k
                    break
        head = " ".join(words[:dup])
        tail = " ".join(words[dup:])
        print(f"\n[{i}] {tokens(c)} ток., {len(words)} слів")
        if head:
            print(f"    ↩ перетин ({dup} слів): …{head[-70:]}")
        print(f"    {tail[:150]}{'…' if len(tail) > 150 else ''}")
        prev_words = words


def find(chunks: list[str], *needles: str) -> list[int]:
    """У яких чанках зустрічається кожен фрагмент."""
    return [i for i, c in enumerate(chunks, 1) if all(n in c for n in needles)]


if __name__ == "__main__":
    print(f"Документ: {tokens(DOC)} токенів, {len(DOC.split())} слів")

    if "--compare" not in sys.argv:
        show(chunk(DOC, size=120, overlap=24), 120, 24)     # 20% перетину
        print("\n" + "─" * 78)
        print("Перетин видно як повтор початку чанка з хвостом попереднього.")
        print("Далі: python chunking.py --compare")
        raise SystemExit

    print("\nТри пари фактів, які мають лишатись разом:")
    print("  A · умова «5 і більше днів»  +  сума «120 грн»          (сусідні речення)")
    print("  B · умова «5 і більше днів»  +  строк «14 банківських»  (різні пункти)")
    print("  C · «оголошена цінність»     +  «10 робочих днів»       (різні розділи)\n")

    PAIRS = (("5 і більше", "120 грн"),
             ("5 і більше", "14 банківських"),
             ("оголошеної цінності", "10 робочих"))

    def row(size, overlap):
        ch = chunk(DOC, size, overlap)
        marks = ["разом  " if find(ch, a, b) else "РВЕТЬСЯ" for a, b in PAIRS]
        print(f"  {size:>3} ток. · перетин {overlap:>2} → {len(ch):>2} чанків   "
              f"A {marks[0]}   B {marks[1]}   C {marks[2]}")

    print("Без перетину:")
    for size in (25, 40, 60, 120):
        row(size, 0)

    print("\nЗ перетином 30%:")
    for size in (25, 40, 60, 120):
        row(size, int(size * 0.3))

    print("\n" + "─" * 78)
    print("Головний рядок — 60 токенів:")
    print("  перетин  0 → пара A РВЕТЬСЯ: сума «120 грн» в одному чанку,")
    print("               умова «5 і більше днів» — у сусідньому")
    print("  перетин 18 → усі три пари разом")
    print("Ось за що платять перетином: за факти, що опинились на межі різання.")
    print()
    print("25 токенів не рятує навіть перетин — чанк менший за саме правило.")
    print("120 тримає все і без перетину, але тягне в промпт цілий розділ.")
    print()
    print("У нашій KB цієї проблеми немає: одне правило = один чанк (~40 ток.),")
    print("бо правила вже нарізані людиною. Чанкінг потрібен там, де джерело —")
    print("суцільний документ: PDF умов, стаття в Confluence, транскрипт дзвінка.")

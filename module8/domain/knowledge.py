def retrieve(query: str, k: int = 3) -> list:
    """Простий лексичний скоринг. Достатньо, щоб показати ефект RAG."""
    words = set(query.lower().replace(",", " ").replace(".", " ").split())
    scored = []
    for keys, text in KB:
        keywords = keys.split()
        exact = len(words & set(keywords))
        partial = sum(
            1 for w in words for kw in keywords
            if len(w) > 4 and (w.startswith(kw[:5]) or kw.startswith(w[:5]))
        )
        scored.append((exact * 2 + partial, text))
    scored.sort(key=lambda x: -x[0])
    hits = [t for s, t in scored[:k] if s > 0]
    return hits or [scored[0][1]]


def as_context(query: str, k: int = 3) -> str:
    """Готовий блок для системного промпта."""
    return "\n\nВитяг з бази знань:\n" + "\n---\n".join(retrieve(query, k))

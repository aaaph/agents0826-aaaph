"""
Чанкінг: як розмір шматка й перетин ламають повʼязані факти.

У нашій KB чанкінг не потрібен — правило вже атомарне (~40 токенів).
Але справжня методичка приходить суцільним текстом, і тоді розбивати
доводиться. Дві біди:

  чанк замалий  → факт відірваний від умови («0.20 м» без «difficult»)
  чанк завеликий → у промпт їде зайве, релевантне тоне

Перетин — страховка від першої: сусідні чанки повторюють одне одного,
тож факт на межі потрапляє в обидва.

    uv run chunking.py            # розбиття з підсвіткою перетину
    uv run chunking.py --compare  # де саме рвуться повʼязані факти
"""

import sys

# Уривок внутрішньої методички — те, що прийшло б із Confluence замість
# готових атомарних правил.
DOC = """Розділ 3. Оцінка точності та критерії прийняття.

3.1. Основною метрикою точності є ATE RMSE. Значення mean і max наводяться
довідково: mean занижує вплив викидів, max чутливий до одного поганого кадру
і сам по собі підставою для висновків не є.

3.2. Сиквенси поділяються на три категорії складності: easy, medium і
difficult. Категорія визначається за динамікою руху, освітленням та наявністю
текстури і фіксується в описі датасету, а не обирається інженером довільно.

3.3. Для кожної категорії встановлено власний поріг прийняття ATE RMSE:
0.06 м, 0.10 м та 0.20 м відповідно. Перевищення порога блокує мердж
до зʼясування причини.

3.4. Перед обрахунком ATE траєкторія вирівнюється: для монокулярних конфігурацій
застосовується Sim(3), оскільки масштаб не є спостережним, для стерео та
стерео-інерціальних — SE(3).

Розділ 5. Діагностика збоїв трекінгу.

5.2. Стійке падіння кількості відстежених фіч нижче 40 протягом більш ніж
трьох секунд перед зривом зазвичай свідчить про невдалу ініціалізацію IMU.
Першими перевіряються gravity alignment та калібрування екстринсиків.

5.6. Розсинхрон камери та IMU понад 5 мс робить інерціальні конфігурації
непорівнюваними між собою. Перевірка синхронізації виконується перед кожною
серією прогонів."""


def tokens(text: str) -> int:
    """Груба оцінка: для української ~1.3 токена на слово."""
    return int(len(text.split()) * 1.3)


def chunk(text: str, size: int, overlap: int) -> list[str]:
    """Найпростіший чанкер: по словах, з фіксованим перетином. Крок = size - overlap."""
    words = text.split()
    per_chunk = max(1, int(size / 1.3))
    step = max(1, int((size - overlap) / 1.3))
    out = []
    for start in range(0, len(words), step):
        piece = words[start : start + per_chunk]
        if not piece:
            break
        out.append(" ".join(piece))
        if start + per_chunk >= len(words):
            break
    return out


def find(chunks: list[str], *needles: str) -> list[int]:
    return [i for i, c in enumerate(chunks, 1) if all(n in c for n in needles)]


def show(chunks: list[str], size: int, overlap: int) -> None:
    print(f"\nрозмір {size} ток. · перетин {overlap} ток. → {len(chunks)} чанків")
    print("─" * 78)
    prev: list[str] = []
    for i, c in enumerate(chunks, 1):
        words = c.split()
        dup = 0
        if prev:
            for k in range(min(len(words), len(prev)), 0, -1):
                if prev[-k:] == words[:k]:
                    dup = k
                    break
        print(f"\n[{i}] {tokens(c)} ток., {len(words)} слів")
        if dup:
            print(f"    ↩ перетин ({dup} слів): …{' '.join(words[:dup])[-70:]}")
        tail = " ".join(words[dup:])
        print(f"    {tail[:150]}{'…' if len(tail) > 150 else ''}")
        prev = words


PAIRS = (
    ("difficult", "0.20"),          # A: категорія (3.2) + її поріг (3.3) — різні пункти
    ("нижче 40", "gravity"),        # B: симптом + що перевіряти — сусідні речення
    ("монокулярних", "Sim(3)"),     # C: конфіг + метод — одне речення (контроль)
)

if __name__ == "__main__":
    print(f"Документ: {tokens(DOC)} токенів, {len(DOC.split())} слів")

    if "--compare" not in sys.argv:
        show(chunk(DOC, 120, 24), 120, 24)
        print("\nДалі: uv run chunking.py --compare")
        raise SystemExit

    print("\nТри пари фактів, які мають лишатись разом:")
    print("  A · «difficult»    + поріг «0.20»       (пункти 3.2 і 3.3 — далеко)")
    print("  B · «нижче 40»     + «gravity»          (сусідні речення)")
    print("  C · «монокулярних» + «Sim(3)»           (одне речення — контроль)\n")

    def row(size: int, overlap: int) -> None:
        ch = chunk(DOC, size, overlap)
        marks = ["разом  " if find(ch, a, b) else "РВЕТЬСЯ" for a, b in PAIRS]
        print(f"  {size:>3} ток. · перетин {overlap:>2} → {len(ch):>2} чанків   "
              f"A {marks[0]}   B {marks[1]}   C {marks[2]}")

    print("Без перетину:")
    for size in (25, 40, 60, 120):
        row(size, 0)
    print("\nЗ перетином 30%:")
    for size in (25, 40, 60, 120):
        row(size, int(size * 0.3))

    print("\n" + "─" * 78)
    print("Перетин не замінює достатній розмір чанка: він зсуває межі, тому пара,")
    print("що випадково вміщалась в один чанк, може розірватись (див. 60 ток.).")
    print("Спершу розмір має перекривати відстань між фактами, потім перетин.")

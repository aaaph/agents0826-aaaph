def retrieve(query: str, k: int = 3) -> list:
    """Лексичний скоринг. Достатньо, щоб показати ефект RAG — і його межу."""
    words = set(query.lower().replace(",", " ").replace(".", " ").split())
    scored = []
    for keys, text in KB:
        keywords = keys.split()
        exact = len(words & set(keywords))
        partial = sum(
            1
            for w in words
            for kw in keywords
            if len(w) > 4 and (w.startswith(kw[:5]) or kw.startswith(w[:5]))
        )
        scored.append((exact * 2 + partial, text))
    scored.sort(key=lambda x: -x[0])
    return [t for s, t in scored[:k] if s > 0]


def as_context(query: str, k: int = 3) -> str:
    """Готовий блок для системного промпта. Порожньо — значить порожньо."""
    hits = retrieve(query, k)
    if not hits:
        return ""
    return "\n\nВитяг з бази знань команди:\n" + "\n---\n".join(hits)
